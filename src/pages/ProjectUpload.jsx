import { FolderUp, Link as LinkIcon, Info } from 'lucide-react'
import DeskLayout, { DeskCard } from '../components/DeskLayout'
import Input from '../components/Input'
import Button from '../components/Button'
import StatusPanel from '../components/StatusPanel'
import SearchableTeamSelect from '../components/SearchableTeamSelect'
import useProjectUpload from '../hooks/useProjectUpload'
import { resultFor, formatDateTime } from '../utils/messages'

export default function ProjectUpload() {
  const {
    availableTeams,
    hasTeams,
    loadingTeams,
    submissionsClosed,
    submissionDeadline,
    teamName,
    setTeamName,
    driveLink,
    setDriveLink,
    phase,
    status,
    submittedData,
    teamNameError,
    driveLinkError,
    submit,
    reset,
    isFormVisible,
  } = useProjectUpload()

  const result = status ? resultFor(status) : null
  const isSuccess = status === 'PROJECT_SUBMITTED'

  return (
    <DeskLayout
      title="Project Upload"
      subtitle="Submit your team's final project for evaluation."
    >
      <DeskCard>
        {!hasTeams && !loadingTeams ? (
          <div className="flex flex-col items-center text-center py-2">
            <div className="w-14 h-14 rounded-full bg-purple-50 border border-purple-100/80 flex items-center justify-center text-purple-600 mb-5 shadow-2xs">
              <Info className="w-6 h-6 stroke-[1.75]" aria-hidden="true" />
            </div>
            <h2 className="text-xl font-bold text-slate-900 mb-2">SUBMISSIONS NOT OPEN</h2>
            <p className="text-slate-600 text-sm leading-relaxed max-w-xs mb-6">
              Project submissions will open once teams have been generated by the organizer.
            </p>
            <div className="w-full px-4 py-3 rounded-2xl bg-purple-50/60 border border-purple-100 text-xs text-purple-700 font-medium">
              Please check back shortly after the team draw!
            </div>
          </div>
        ) : submissionsClosed && !loadingTeams ? (
          <div className="flex flex-col items-center text-center py-2">
            <div className="w-14 h-14 rounded-full bg-purple-50 border border-purple-100/80 flex items-center justify-center text-purple-600 mb-5 shadow-2xs">
              <Info className="w-6 h-6 stroke-[1.75]" aria-hidden="true" />
            </div>
            <h2 className="text-xl font-bold text-slate-900 mb-2">SUBMISSIONS CLOSED</h2>
            <p className="text-slate-600 text-sm leading-relaxed max-w-xs mb-6">
              The project submission window has closed
              {submissionDeadline ? ` (${formatDateTime(submissionDeadline)})` : ''}.
            </p>
            <div className="w-full px-4 py-3 rounded-2xl bg-purple-50/60 border border-purple-100 text-xs text-purple-700 font-medium">
              Please reach out to an organizer if you believe this is a mistake.
            </div>
          </div>
        ) : isFormVisible ? (
          <div className="flex flex-col items-center text-center">
            {/* Circular Folder Icon Container */}
            <div className="w-14 h-14 rounded-full bg-purple-50 border border-purple-100/80 flex items-center justify-center text-purple-600 mb-6 shadow-2xs">
              <FolderUp className="w-6 h-6 stroke-[1.75]" aria-hidden="true" />
            </div>

            <form onSubmit={submit} className="w-full flex flex-col gap-5">
              {/* Searchable Team Selector */}
              <SearchableTeamSelect
                label="TEAM NAME"
                teams={availableTeams}
                value={teamName}
                onChange={(val) => setTeamName(val)}
                error={teamNameError}
                disabled={phase === 'loading' || loadingTeams}
                placeholder={
                  loadingTeams ? 'Loading generated teams…' : 'Search or select your team...'
                }
              />

              <div className="flex flex-col gap-1.5 text-left">
                <Input
                  label="GOOGLE DRIVE LINK"
                  type="url"
                  inputMode="url"
                  icon={LinkIcon}
                  placeholder="https://drive.google.com/..."
                  value={driveLink}
                  onChange={(e) => setDriveLink(e.target.value)}
                  error={driveLinkError}
                  disabled={phase === 'loading'}
                  maxLength={500}
                />
                <p className="text-xs text-slate-500 font-normal leading-relaxed px-1">
                  Upload your team's presentation, code, or project files to Google Drive and paste the shared link above.
                </p>
              </div>

              <Button
                type="submit"
                icon={FolderUp}
                loading={phase === 'loading'}
                loadingLabel="Submitting…"
                disabled={!teamName.trim() || !driveLink.trim() || phase === 'loading'}
              >
                SUBMIT PROJECT
              </Button>
            </form>
          </div>
        ) : (
          <div className="flex flex-col gap-6">
            <StatusPanel
              tone={result.tone}
              title={result.title}
              name={isSuccess && submittedData?.teamName ? `Team: ${submittedData.teamName}` : undefined}
              description={result.description}
            />

            {!isSuccess && (
              <Button variant="secondary" onClick={reset}>
                TRY AGAIN
              </Button>
            )}
          </div>
        )}
      </DeskCard>
    </DeskLayout>
  )
}
