import { useCallback, useEffect, useRef, useState } from 'react'
import { api } from '../services/api'

function isValidUrl(value) {
  if (!value) return false
  try {
    const url = new URL(value)
    return url.protocol === 'http:' || url.protocol === 'https:'
  } catch {
    return false
  }
}

export default function useProjectUpload() {
  const [availableTeams, setAvailableTeams] = useState([])
  const [hasTeams, setHasTeams] = useState(true)
  const [loadingTeams, setLoadingTeams] = useState(true)

  const [teamName, setTeamNameState] = useState('')
  const [driveLink, setDriveLinkState] = useState('')
  const [phase, setPhase] = useState('idle') // idle | loading | done
  const [status, setStatus] = useState(null)
  const [submittedData, setSubmittedData] = useState(null)

  const [teamNameError, setTeamNameError] = useState('')
  const [driveLinkError, setDriveLinkError] = useState('')

  const busy = useRef(false)

  const loadTeams = useCallback(async () => {
    setLoadingTeams(true)
    try {
      const data = await api.getPublicTeams()
      const list = data.teams || []
      setAvailableTeams(list)
      setHasTeams(list.length > 0)
    } catch {
      // If fetching fails, default to showing no teams available
      setAvailableTeams([])
      setHasTeams(false)
    } finally {
      setLoadingTeams(false)
    }
  }, [])

  useEffect(() => {
    loadTeams()
  }, [loadTeams])

  const setTeamName = useCallback((value) => {
    setTeamNameState(value)
    setTeamNameError('')
  }, [])

  const setDriveLink = useCallback((value) => {
    setDriveLinkState(value)
    setDriveLinkError('')
  }, [])

  const submit = useCallback(
    async (event) => {
      if (event) event.preventDefault()
      if (busy.current) return

      const cleanTeam = teamName.trim()
      const cleanLink = driveLink.trim()

      let hasError = false
      if (!cleanTeam) {
        setTeamNameError('Please select your team.')
        hasError = true
      }

      if (!cleanLink) {
        setDriveLinkError('Please enter your Google Drive project link.')
        hasError = true
      } else if (!isValidUrl(cleanLink)) {
        setDriveLinkError('Please enter a valid URL starting with http:// or https://')
        hasError = true
      }

      if (hasError) return

      busy.current = true
      setTeamNameError('')
      setDriveLinkError('')
      setPhase('loading')

      try {
        const data = await api.submitProject(cleanTeam, cleanLink)
        setStatus(data.status || 'PROJECT_SUBMITTED')
        setSubmittedData(
          data.submission || { teamName: cleanTeam, driveLink: cleanLink }
        )
      } catch (error) {
        setStatus(error.status || 'SERVICE_UNAVAILABLE')
        setSubmittedData(null)
        if (error.status === 'INVALID_TEAM_NAME' || error.status === 'TEAM_NOT_FOUND') {
          setTeamNameError('Please select a team generated by the organizer.')
        } else if (error.status === 'TEAMS_NOT_GENERATED') {
          setTeamNameError('Project submissions are not open yet.')
        } else if (error.status === 'INVALID_DRIVE_LINK') {
          setDriveLinkError('Please enter a valid Google Drive URL.')
        }
      } finally {
        busy.current = false
        setPhase('done')
      }
    },
    [teamName, driveLink]
  )

  const reset = useCallback(() => {
    setTeamNameState('')
    setDriveLinkState('')
    setPhase('idle')
    setStatus(null)
    setSubmittedData(null)
    setTeamNameError('')
    setDriveLinkError('')
    loadTeams()
  }, [loadTeams])

  return {
    availableTeams,
    hasTeams,
    loadingTeams,
    teamName,
    setTeamName,
    driveLink,
    setDriveLink,
    phase,
    status,
    submittedData,
    teamNameError,
    driveLinkError,
    submit,
    reset,
    isFormVisible: phase !== 'done',
  }
}
