/**
 * Picks `count` distinct names.
 *
 * Shuffled, so consecutive draws do not hand out the same names in the same
 * order — pressing "randomize again" should feel like a genuinely new draw,
 * not the same teams relabelled.
 *
 * If more teams are requested than there are names, the list is reused with a
 * numeric suffix ("Insight Labs 2"). Uniqueness within a draw is what matters,
 * and this keeps it without inventing filler names nobody vetted.
 *
 * @param {number} count
 * @param {() => number} randomInt receives an exclusive upper bound
 * @returns {string[]} exactly `count` unique names
 */
import { text } from './normalize.js';

/**
 * Checks if a given team name matches any team name generated by the randomizer.
 * Accepts exact base names (case-insensitive) as well as numbered variants like "Insight Labs 2".
 *
 * @param {string} name
 * @returns {boolean}
 */
export function isValidTeamName(name) {
  const clean = text(name).toLowerCase();
  if (!clean) return false;

  return TEAM_NAMES.some((base) => {
    const lowerBase = base.toLowerCase();
    if (clean === lowerBase) return true;
    const regex = new RegExp(`^${lowerBase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s+\\d+$`);
    return regex.test(clean);
  });
}

export function pickTeamNames(count, randomInt) {
  const pool = [...TEAM_NAMES];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = randomInt(i + 1);
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  const names = [];
  for (let i = 0; i < count; i++) {
    const base = pool[i % pool.length];
    const round = Math.floor(i / pool.length);
    names.push(round === 0 ? base : `${base} ${round + 1}`);
  }
  return names;
}
