/**
 * POST /api/project-upload  { teamName, driveLink }
 *
 * Public attendee-facing endpoint for project submissions.
 *
 * Inputs are validated server-side, rate-limited, and appended to the existing
 * ProjectUploads Google Sheet tab.
 */

import { submitProjectUpload, safeLink } from './_lib/projects.js';
import { text } from './_lib/normalize.js';
import { rateLimit, ATTENDEE_LIMIT } from './_lib/rateLimit.js';
import { send, requireMethod, readJsonBody, clientKey, fail, STATUS } from './_lib/responses.js';

export default async function handler(req, res) {
  if (!requireMethod(req, res, 'POST')) return;

  const limit = rateLimit(`project-upload:${clientKey(req)}`, ATTENDEE_LIMIT);
  if (!limit.allowed) {
    res.setHeader('Retry-After', String(limit.retryAfterSeconds));
    return send(res, 429, {
      success: false,
      status: STATUS.RATE_LIMITED,
      message: 'Too many attempts. Please wait a moment and try again.',
    });
  }

  const body = await readJsonBody(req);
  if (!body) {
    return send(res, 400, { success: false, status: STATUS.INVALID_REQUEST });
  }

  const teamName = typeof body.teamName === 'string' ? text(body.teamName) : '';
  const driveLink = typeof body.driveLink === 'string' ? safeLink(body.driveLink) : '';

  if (!teamName) {
    return send(res, 400, {
      success: false,
      status: STATUS.INVALID_TEAM_NAME,
      message: 'Please enter your team name.',
    });
  }

  if (!driveLink) {
    return send(res, 400, {
      success: false,
      status: STATUS.INVALID_DRIVE_LINK,
      message: 'Please enter a valid Google Drive URL (starting with http:// or https://).',
    });
  }

  try {
    const result = await submitProjectUpload({ teamName, driveLink });

    if (result.status === STATUS.SUBMISSIONS_CLOSED) {
      return send(res, 400, {
        success: false,
        status: STATUS.SUBMISSIONS_CLOSED,
        message: 'The project submission window has closed.',
      });
    }

    if (result.status === STATUS.TEAMS_NOT_GENERATED) {
      return send(res, 400, {
        success: false,
        status: STATUS.TEAMS_NOT_GENERATED,
        message: 'Project submissions will open once teams have been generated by the organizer.',
      });
    }

    if (result.status === STATUS.TEAM_ALREADY_SUBMITTED) {
      // 409: the request was understood and refused because it conflicts with
      // state that already exists — this team already has a submission.
      return send(res, 409, {
        success: false,
        status: STATUS.TEAM_ALREADY_SUBMITTED,
        message: 'This team has already submitted a project.',
      });
    }

    if (result.status === STATUS.INVALID_TEAM_NAME || result.status === STATUS.TEAM_NOT_FOUND) {
      return send(res, 400, {
        success: false,
        status: STATUS.INVALID_TEAM_NAME,
        message: 'Please select a team generated by the organizer.',
      });
    }

    if (result.status === STATUS.INVALID_DRIVE_LINK) {
      return send(res, 400, {
        success: false,
        status: STATUS.INVALID_DRIVE_LINK,
        message: 'Please enter a valid Google Drive URL (starting with http:// or https://).',
      });
    }

    return send(res, 200, {
      success: true,
      status: STATUS.PROJECT_SUBMITTED,
      submission: result.submission,
    });
  } catch (error) {
    return fail(res, error, 'api/project-upload');
  }
}
